'''Write a Python program to find the average mileage of a car. '''
total_distance = float(input("Enter the total distance covered (in km): "))
total_fuel_consumed = float(input("Enter the total fuel consumed (in liters): "))
average_mileage = total_distance / total_fuel_consumed
#output:
print("Average Mileage of the car =", average_mileage, "km/l")
